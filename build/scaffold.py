#!/usr/bin/env python3
"""Page template for a module that has not been designed yet.

The preamp and equaliser sections are built from this. It deliberately contains no circuit
values, no part numbers and no performance figures: none exist, and inventing them would
make the site look authoritative about hardware nobody has drawn. Each page states what it
will hold and what has to be decided first, so the section is a checklist rather than a
placeholder.

When a module gets a real design.py and KiCad project, replace its content_*.py the way
content_compressor.py is written, and drop `--module <slug>` into _data.py to generate the
interactive schematics.
"""
from shell import table


def _banner(name):
    return f"""<div class="note warn">
  <h4>Nothing here is designed yet</h4>
  <p>The {name} module has no schematic, no netlist and no bill of materials. This section is
  a <strong>template</strong> that mirrors the structure of the
  <a href="../compressor/index.html">compressor documentation</a>, so the shape of the work is
  visible before the work starts. Every figure below is deliberately blank rather than
  guessed.</p>
</div>"""


def build(name, slug, tagline, blurb, sections, decisions, specs):
    """Return (NAV, PAGES) for a not-yet-designed module.

    sections  [(filename, nav-title, heading, what the page will explain, [open questions])]
    decisions [(question, why it matters)]
    specs     [(row label, unit)]  - the specification table, with values left blank
    """
    nav_signal = [(f, '%02d' % (i + 2), t) for i, (f, t, _, _, _) in enumerate(sections)]
    NAV = [("Start here", [("index.html", "01", "Overview")]),
           ("Planned sections", nav_signal),
           ("Practical", [("panel.html", '%02d' % (len(sections) + 2), "The front panel")])]

    PAGES = {}

    PAGES['index.html'] = ("Overview", f"""
<p class="eyebrow">{name} module</p>
<h1>The {slug} module</h1>
<p class="lede">{tagline}</p>
{_banner(name)}
<p>{blurb}</p>

<h2>Specifications</h2>
<p>Filled in once there is a circuit to measure or calculate from. The rows fixed by the
500-series format are the only numbers known today.</p>
""" + table(["Specification", "Value", "Fixed by"],
            [[s, "&mdash;", u] for s, u in specs], ["r", "n", ""]) + f"""

<h2>What has to be decided first</h2>
<p>These are the choices that determine everything else. Until they are made, the pages in
this section have nothing to say.</p>
""" + table(["Decision", "Why it drives the rest"],
            decisions, ["r", ""]) + """

<h2>How this section will be built</h2>
<p>The compressor section is generated from a single source of truth: a
<code>design.py</code> holding the netlist as data, which the KiCad schematic is verified
against pin by pin. The interactive schematics, the component data behind them and the
bill-of-materials counts all come from that one file.</p>
<p>This module follows the same route. Nothing here becomes real documentation until there
is a <code>design.py</code> to generate it from.</p>
""")

    for i, (fname, navtitle, heading, purpose, questions) in enumerate(sections):
        q = ''.join('<li>%s</li>' % x for x in questions)
        PAGES[fname] = (navtitle, f"""
<p class="eyebrow">Planned section {i + 2:02d}</p>
<h1>{heading}</h1>
<p class="lede">{purpose}</p>
{_banner(name)}
<h2>Open questions</h2>
<ul>{q}</ul>
<h2>What this page will contain</h2>
<p>Once the section is drawn: an interactive schematic of the sheet, a walk through what each
part does and why it is that value, and the measurements or calculations behind any figure
quoted. The compressor section shows the format.</p>
""")

    PAGES['panel.html'] = ("The front panel", f"""
<p class="eyebrow">Practical</p>
<h1>The front panel</h1>
<p class="lede">Controls, legend and hole positions for the {slug}, on the same 1.5&nbsp;inch
500-series faceplate as the rest of the desk.</p>
{_banner(name)}
<h2>What is already fixed</h2>
<p>The panel outline does not depend on the circuit. Every module in the desk shares it.</p>
""" + table(["Dimension", "Value"],
            [["Panel width", "38.10 mm"], ["Panel height", "133.35 mm"],
             ["Panel thickness", "3.18 mm"],
             ["Mounting holes", "&#216;3.18 mm, c'sunk 82&deg; to &#216;5.72 mm"],
             ["Hole centres", "x = 19.05 mm, y = 3.96 and 129.39 mm"]],
            ["r", "n"]) + """
<h2>What is not</h2>
<p>Control count, control type and legend all follow from the circuit. The compressor's panel
is generated by a script that takes one definition of the controls and produces the mockup,
a 1:1 technical drawing and a DXF, checking every hole for clearance on each build. The same
script will produce this panel once there is a control set to give it.</p>
""")
    return NAV, PAGES
